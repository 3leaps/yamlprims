#!/usr/bin/env bash
# SPDX-License-Identifier: MIT OR Apache-2.0
# Build the TypeScript package and test what it would publish:
#
# 0. the only unsafe-code allowances in the WebAssembly crate are on its
#    exported functions;
# 1. build the module (wasm32, no imports), embed it, compile with the pinned
#    TypeScript (npm ci from the committed lockfile), and npm pack;
# 2. install the tarball into a throwaway project and run the API, allocation,
#    and conformance vector tests against it (node:test, no skips);
# 3. its conformance vector results equal Rust's, byte for byte.
#
# Copies the packed tarball into TS_CHECK_KEEP=<dir> when set.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
python="${PYTHON:-python3}"
pkg="${root}/bindings/typescript"
work="$(mktemp -d "${TMPDIR:-/tmp}/yamlprims-ts.XXXXXX")"
trap 'rm -rf "${work}"' EXIT
cd "${root}"

for license in LICENSE-MIT LICENSE-APACHE NOTICE; do
  cmp -s "${license}" "${pkg}/${license}" ||
    { echo "ts-check: bindings/typescript/${license} differs from ${license}" >&2; exit 1; }
done

# In every Rust file of the crate, each `#[allow(unsafe_code)]` must sit
# directly above `#[no_mangle]`, and no other line may mention unsafe.
"${python}" -I - "${pkg}" <<'PY'
import pathlib, sys
crate = pathlib.Path(sys.argv[1])
files = sorted(p for p in crate.rglob("*.rs") if "target" not in p.relative_to(crate).parts)
if crate / "src" / "lib.rs" not in files:
    sys.exit("ts-check: the WebAssembly crate has no src/lib.rs")
bad = []
for path in files:
    lines = path.read_text(encoding="utf-8").splitlines()
    for i, l in enumerate(lines):
        if "unsafe" not in l or l.lstrip().startswith(("//", "///", "//!")):
            continue
        if l.strip() == "#[allow(unsafe_code)]" and i + 1 < len(lines) and lines[i + 1].strip() == "#[no_mangle]":
            continue
        bad.append(f"{path.relative_to(crate)}:{i + 1}")
if bad:
    sys.exit(f"ts-check: unsafe outside an export allowance at {bad}")
PY

target_dir="${CARGO_TARGET_DIR:-${root}/target}/wasm"
# Panic locations embed source paths; map the checkout, the Cargo home and
# the rustup home to fixed names so the module carries no build-host path.
physical_root="$(pwd -P)"
cargo_home="${CARGO_HOME:-${HOME}/.cargo}"
rustup_home="${RUSTUP_HOME:-${HOME}/.rustup}"
CARGO_TARGET_DIR="${target_dir}" \
  RUSTFLAGS="-Clink-arg=--max-memory=134217728 --remap-path-prefix=${physical_root}=/yamlprims --remap-path-prefix=${cargo_home}=/cargo --remap-path-prefix=${rustup_home}=/rustup" \
  cargo build --quiet --locked --release \
  --manifest-path "${pkg}/Cargo.toml" --target wasm32-unknown-unknown
module="${target_dir}/wasm32-unknown-unknown/release/yamlprims_wasm.wasm"
"${python}" -I scripts/host-path-check.py "${module}" "${physical_root}" "${cargo_home}" "${rustup_home}" "${HOME}" ||
  { echo "ts-check: the module embeds a build-host path" >&2; exit 1; }
node --input-type=module - "${module}" <<'JS'
import { readFileSync } from "node:fs";
const m = new WebAssembly.Module(readFileSync(process.argv[2]));
const imports = WebAssembly.Module.imports(m);
if (imports.length) { console.error("ts-check: the module has imports:", imports); process.exit(1); }
const inst = new WebAssembly.Instance(m, {});
const mem = inst.exports.memory;
const curPages = mem.buffer.byteLength / 65536;
let grewPastMax = false;
try {
  mem.grow(2049 - curPages);
  grewPastMax = true;
} catch (err) {
  if (!(err instanceof RangeError)) {
    console.error("ts-check: unexpected error growing past 2048 pages:", err);
    process.exit(1);
  }
}
if (grewPastMax) {
  console.error("ts-check: module allowed linear memory growth past 2048 pages (128 MiB)");
  process.exit(1);
}
mem.grow(2048 - curPages);
if (mem.buffer.byteLength !== 134217728) {
  console.error("ts-check: expected 134217728 bytes at 2048 pages, got", mem.buffer.byteLength);
  process.exit(1);
}
JS

# The module is embedded as base64 so the package loads with no file or
# network read, in every runtime. The generated file is not tracked.
{
  echo "// Generated by scripts/ts-check.sh from the yamlprims-wasm module. Do not edit."
  printf 'export const WASM_BASE64: string =\n  "%s";\n' "$(base64 < "${module}" | tr -d '\n')"
} > "${pkg}/ts/wasm.ts"

(cd "${pkg}" && npm ci --ignore-scripts --no-audit --no-fund --silent && rm -rf dist && node_modules/.bin/tsc -p tsconfig.json)
version="$(tr -d ' \t\r\n' < VERSION)"
tarball="$(cd "${pkg}" && npm pack --silent --pack-destination "${work}")"
tarball="${work}/${tarball##*/}"
[ "${tarball##*/}" = "3leaps-yamlprims-${version}.tgz" ] || { echo "ts-check: unexpected tarball ${tarball##*/}" >&2; exit 1; }
listed="$(tar -tzf "${tarball}" | LC_ALL=C sort | tr '\n' ' ')"
want="package/LICENSE-APACHE package/LICENSE-MIT package/NOTICE package/README.md package/dist/index.d.ts package/dist/index.js package/dist/wasm.d.ts package/dist/wasm.js package/package.json "
[ "${listed}" = "${want}" ] || { echo "ts-check: tarball contents differ: ${listed}" >&2; exit 1; }

# A consumer project: the tarball, nothing else, no registry access.
mkdir "${work}/consumer"
cp -R "${pkg}/test" "${work}/consumer/test"
printf '{"name":"consumer","private":true,"type":"module"}\n' > "${work}/consumer/package.json"
(cd "${work}/consumer" && npm install --offline --ignore-scripts --no-audit --no-fund --silent "${tarball}")

(cd "${work}/consumer" && YAMLPRIMS_VECTORS_FILE="${root}/conformance/vectors/cases.jsonl" \
  YAMLPRIMS_RESULTS_OUT="${work}/ts.results" YAMLPRIMS_VERSION="${version}" \
  node --test --test-reporter=tap test/api.test.mjs test/allocation.test.mjs test/corpus.test.mjs > "${work}/test.tap" 2>&1) ||
  { cat "${work}/test.tap" >&2; exit 1; }

# Every test must pass: none failed, cancelled, skipped or todo, and the
# files did run.
"${python}" -I - "${work}/test.tap" <<'PY' ||
import re, sys
text = open(sys.argv[1], encoding="utf-8").read()
counts = {k: int(v) for k, v in re.findall(r"^# (tests|pass|fail|cancelled|skipped|todo) (\d+)$", text, re.M)}
ok = (len(counts) == 6 and counts["pass"] == counts["tests"] and counts["tests"] >= 14
      and not any(counts[k] for k in ("fail", "cancelled", "skipped", "todo")))
sys.exit(0 if ok else f"summary {counts}")
PY
  { cat "${work}/test.tap" >&2; echo "ts-check: tests failed, skipped or todo" >&2; exit 1; }

cargo build --quiet --locked -p yamlprims --example structcorpus >/dev/null
rust_driver="${CARGO_TARGET_DIR:-${root}/target}/debug/examples/structcorpus"
"${rust_driver}" --crosscheck-jsonl < "${root}/conformance/vectors/cases.jsonl" > "${work}/rust.results"

"${python}" -I - "${work}/rust.results" "${work}/ts.results" <<'PY'
import json, pathlib, sys
rust_lines = [json.loads(l) for l in pathlib.Path(sys.argv[1]).read_text(encoding="utf-8").splitlines() if l.strip()]
ts_lines = [json.loads(l) for l in pathlib.Path(sys.argv[2]).read_text(encoding="utf-8").splitlines() if l.strip()]
if len(rust_lines) != len(ts_lines):
    sys.exit(f"ts-check: count mismatch rust={len(rust_lines)} ts={len(ts_lines)}")
mismatches = []
for r, t in zip(rust_lines, ts_lines):
    if r["id"] != t["id"]:
        mismatches.append(f"id mismatch: {r['id']} vs {t['id']}")
    elif r["wire"] != t["wire"]:
        mismatches.append(f"{r['id']} [wire]:\n  rust: {r['wire']}\n  ts:   {t['wire']}")
    elif r["plain"] != t["plain"]:
        mismatches.append(f"{r['id']} [plain]:\n  rust: {r['plain']}\n  ts:   {t['plain']}")
    elif r.get("emit", "") != t.get("emit", ""):
        mismatches.append(f"{r['id']} [emit]:\n  rust: {r.get('emit', '')}\n  ts:   {t.get('emit', '')}")
    elif r.get("ijson", "") != t.get("ijson", ""):
        mismatches.append(f"{r['id']} [ijson]:\n  rust: {r.get('ijson', '')}\n  ts:   {t.get('ijson', '')}")
if mismatches:
    for m in mismatches[:10]:
        print(m, file=sys.stderr)
    sys.exit(f"ts-check: {len(mismatches)} mismatches vs Rust")
print(f"ts-check: conformance vectors agree with Rust ({len(ts_lines)} cases)", file=sys.stderr)
PY

if [ -n "${TS_CHECK_KEEP:-}" ]; then cp "${tarball}" "${TS_CHECK_KEEP}/"; fi
echo "[ok] ts-check"
